/**
 * @mariachi/design/build: Node API. `buildDesign` turns a design config into one CSS file;
 * `writePackageAssets` is what the package's own build runs to produce `dist/css`, `dist/tokens`
 * and `dist/catalog.json`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { componentList, contrastPairs, tokenList } from './contract';
import type { ComponentExample } from './contract/component';
import { componentExamples } from './components/examples';
import { type DesignConfig, defineDesign, type ResolvedDesign } from './design';
import { checkTheme, type ThemeCheck } from './engine/check';
import { expandComponentVars, unknownDefaultRefs, unknownVars } from './engine/css-vars';
import { emitThemeCss } from './engine/emit-css';
import { emitDtcg } from './engine/emit-dtcg';
import { emitOverridesCss } from './engine/overrides';
import { emitTailwindCss } from './engine/tailwind';
import type { Theme } from './engine/theme';
import { DesignError } from './errors';
import { presets } from './presets';

export * from './index';

/** Foundation files, in output order. */
export const BASE_FILES = ['layers.css', 'reset.css', 'base.css', 'forms.css', 'motion.css'];

/** The package root (works from `src/` in tests and from `dist/` when installed). */
export function packageRoot(): string {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function read(file: string): string {
  if (!fs.existsSync(file)) throw new DesignError('design/missing-asset', `Missing ${file}`);
  return fs.readFileSync(file, 'utf8');
}

/** Raw source CSS checked for unknown tokens, then expanded with component defaults. */
export function compileSourceCss(css: string, file: string): string {
  const unknown = unknownVars(css);
  if (unknown.length > 0) {
    throw new DesignError(
      'design/unknown-token',
      `${file} references unknown token(s):\n${unknown.map((u) => `  ${file}:${u.line} ${u.name}`).join('\n')}`,
      { file, unknown },
    );
  }
  return expandComponentVars(css);
}

/** Reads compiled CSS from `dist/css`, or compiles it from `src` when the package isn't built. */
export class CssSource {
  constructor(private readonly root: string = packageRoot()) {}

  private compiled(rel: string): string | undefined {
    const file = path.join(this.root, 'dist', 'css', rel);
    return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : undefined;
  }

  base(): string {
    return (
      this.compiled('base.css') ??
      BASE_FILES.map((f) => compileSourceCss(read(path.join(this.root, 'src', 'css', f)), `src/css/${f}`)).join('\n')
    );
  }

  component(name: string): string {
    return (
      this.compiled(`components/${name}.css`) ??
      compileSourceCss(read(path.join(this.root, 'src', 'components', name, `${name}.css`)), `src/components/${name}/${name}.css`)
    );
  }
}

export interface BuildDesignOptions {
  /** Directory `replace` paths are relative to (the config file's directory). Default: cwd. */
  cwd?: string;
  /** Write the CSS here (relative to `cwd`). */
  outFile?: string;
  /** Minify with lightningcss (an optional peer dependency). */
  minify?: boolean;
}

export interface BuildDesignResult {
  css: string;
  design: ResolvedDesign;
  check: ThemeCheck;
  outFile?: string;
}

function wrapReplacement(css: string, name: string, file: string): string {
  const layered = /@layer\s+mariachi\.components/.test(css) ? css : `@layer mariachi.components {\n${css}\n}`;
  return `/* ${name}: replaced by ${file} */\n${layered}`;
}

async function minifyCss(css: string, filename: string): Promise<string> {
  let lightning: typeof import('lightningcss');
  try {
    lightning = await import('lightningcss');
  } catch {
    throw new DesignError('design/missing-asset', 'minify requires lightningcss: install it as a dev dependency');
  }
  return Buffer.from(lightning.transform({ filename, code: Buffer.from(css), minify: true }).code).toString('utf8');
}

/**
 * Builds one CSS file from a design config: foundation, the selected components (with any
 * replacements), the base theme, and a block with only the tokens the config changes (or a full
 * theme under `config.name`). Also checks contrast on the merged theme.
 */
export async function buildDesign(config: DesignConfig | ResolvedDesign, options: BuildDesignOptions = {}): Promise<BuildDesignResult> {
  const design = 'theme' in config ? config : defineDesign(config);
  const cwd = options.cwd ?? process.cwd();
  const source = new CssSource();
  const parts = ['/* Generated by @mariachi/design buildDesign. Do not edit; change the config instead. */', source.base()];
  for (const name of design.components) {
    const replacement = design.config.replace?.[name];
    if (replacement) {
      const file = path.resolve(cwd, replacement);
      parts.push(wrapReplacement(read(file), name, replacement));
    } else {
      parts.push(source.component(name));
    }
  }
  if (design.config.name) {
    parts.push(emitThemeCss(design.theme));
  } else {
    parts.push(emitThemeCss(design.base));
    const overrides = emitOverridesCss(design.base, design.theme);
    if (overrides) parts.push(overrides);
  }
  let css = parts.join('\n');
  if (options.minify) css = await minifyCss(css, options.outFile ?? 'design.css');
  let outFile: string | undefined;
  if (options.outFile) {
    outFile = path.resolve(cwd, options.outFile);
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, css);
  }
  return { css, design, check: checkTheme(design.theme), outFile };
}

// ---------------------------------------------------------------------------------------------
// Catalog: everything the explorer, docs and coding agents need, as JSON.

export interface CatalogToken {
  path: string;
  cssVar: string;
  kind: string;
  description: string;
  default?: unknown;
}

export interface Catalog {
  version: string;
  presets: { name: string; label: string; description: string; extends?: string; tokens: Theme['tokens'] }[];
  semantic: CatalogToken[];
  components: {
    name: string;
    title: string;
    category: string;
    description: string;
    useWhen: string;
    anatomy: Record<string, string>;
    requires: string[];
    a11y: string[];
    tokens: CatalogToken[];
    examples: ComponentExample[];
  }[];
  contrastPairs: typeof contrastPairs;
}

const catalogToken = (t: (typeof tokenList)[number]): CatalogToken => ({
  path: t.path,
  cssVar: t.cssVar,
  kind: t.def.kind,
  description: t.def.description,
  default: t.def.default,
});

export function buildCatalog(version: string): Catalog {
  return {
    version,
    presets: Object.values(presets as Record<string, Theme>).map((p) => ({
      name: p.name,
      label: p.label,
      description: p.description,
      extends: p.extends,
      tokens: p.tokens,
    })),
    semantic: tokenList.filter((t) => !t.path.startsWith('components.')).map(catalogToken),
    components: componentList.map((c) => ({
      name: c.name,
      title: c.title,
      category: c.category,
      description: c.description,
      useWhen: c.useWhen,
      anatomy: c.anatomy,
      requires: c.requires ?? [],
      a11y: c.a11y,
      tokens: tokenList.filter((t) => t.path.startsWith(`components.${camel(c.name)}.`)).map(catalogToken),
      examples: componentExamples.find((e) => e.component === c.name)?.examples ?? [],
    })),
    contrastPairs,
  };
}

const camel = (s: string) => s.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());

