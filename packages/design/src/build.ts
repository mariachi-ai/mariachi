// Package assets.

export interface PackageAssets {
  files: Record<string, string>;
}

/**
 * Every file the package publishes besides the JS: compiled CSS, per-preset themes and DTCG JSON,
 * and the catalog. Throws on unknown tokens in CSS or in contract defaults, and on components
 * missing a CSS file or examples.
 */
export function packageAssets(root: string = packageRoot()): PackageAssets {
  const badDefaults = unknownDefaultRefs();
  if (badDefaults.length > 0) {
    throw new DesignError(
      'design/unknown-token',
      `Contract defaults reference unknown tokens:\n${badDefaults.map((b) => `  ${b.path} → ${b.name}`).join('\n')}`,
    );
  }
  const version = JSON.parse(read(path.join(root, 'package.json'))).version as string;
  const files: Record<string, string> = {};
  const header = `/* @mariachi/design ${version} */\n`;
  const base = BASE_FILES.map((f) => compileSourceCss(read(path.join(root, 'src', 'css', f)), `src/css/${f}`)).join('\n');
  files['css/base.css'] = header + base;
  const components: string[] = [];
  for (const c of componentList) {
    if (!componentExamples.some((e) => e.component === c.name && e.examples.length > 0)) {
      throw new DesignError('design/missing-asset', `Component "${c.name}" has no examples`);
    }
    const css = compileSourceCss(read(path.join(root, 'src', 'components', c.name, `${c.name}.css`)), `src/components/${c.name}/${c.name}.css`);
    files[`css/components/${c.name}.css`] = header + css;
    components.push(css);
  }
  files['css/components.css'] = header + components.join('\n');
  files['css/mariachi.css'] = `${header}${base}\n${components.join('\n')}`;
  for (const theme of Object.values(presets as Record<string, Theme>)) {
    files[`css/themes/${theme.name}.css`] = emitThemeCss(theme);
    files[`tokens/${theme.name}.json`] = `${JSON.stringify(emitDtcg(theme), null, 2)}\n`;
  }
  files['css/tailwind.css'] = emitTailwindCss();
  files['catalog.json'] = `${JSON.stringify(buildCatalog(version), null, 2)}\n`;
  return { files };
}

/** Writes `packageAssets()` under `dist/`. */
export function writePackageAssets(root: string = packageRoot()): string[] {
  const { files } = packageAssets(root);
  for (const [rel, content] of Object.entries(files)) {
    const file = path.join(root, 'dist', rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
  return Object.keys(files);
}
