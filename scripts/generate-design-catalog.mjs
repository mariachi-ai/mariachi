#!/usr/bin/env node
// Generates packages/core/docs/design-catalog.md from @mariachi/design's built catalog
// (packages/design/dist/catalog.json). `--check` fails if the file is stale (CI runs it after build).
import fs from 'node:fs';

const OUT = 'packages/core/docs/design-catalog.md';
const SOURCE = 'packages/design/dist/catalog.json';
const CATEGORY_TITLES = {
  layout: 'Layout',
  actions: 'Actions',
  forms: 'Forms',
  data: 'Data display',
  navigation: 'Navigation',
  feedback: 'Feedback',
  overlays: 'Overlays',
  content: 'Content',
  ai: 'AI patterns',
};

if (!fs.existsSync(SOURCE)) {
  console.error(`${SOURCE} is missing: run pnpm build first`);
  process.exit(1);
}
const catalog = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
// Prose cells: escape angle brackets so a description mentioning <select> isn't rendered as HTML.
const text = (s) => cell(s).replace(/</g, '&lt;').replace(/>/g, '&gt;');
const lines = [
  '# Design catalog',
  '',
  '<!-- Generated by `pnpm docs:catalog` from @mariachi/design (dist/catalog.json). Do not edit. -->',
  '',
  `${catalog.components.length} components and ${catalog.presets.length} presets. How to use and override them: [design.md](./design.md).`,
  'Every component and preset is browsable in the [explorer](./explorer.md).',
  '',
  '## Presets',
  '',
  '| Preset | Description |',
  '| --- | --- |',
  ...catalog.presets.map((p) => `| \`${p.name}\` | ${text(p.description)} |`),
  '',
];
for (const [key, title] of Object.entries(CATEGORY_TITLES)) {
  const group = catalog.components.filter((c) => c.category === key);
  if (group.length === 0) continue;
  lines.push(`## ${title}`, '', '| Component | What it is | Use it when | Markup |', '| --- | --- | --- | --- |');
  for (const c of group) {
    const markup = Object.keys(c.anatomy).filter((k) => k.startsWith('.') || k.startsWith('[')).map((k) => `\`${k}\``).join(' ');
    lines.push(`| ${c.title} (\`${c.name}\`) | ${text(c.description)} | ${text(c.useWhen)} | ${cell(markup)} |`);
  }
  lines.push('');
}
const content = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== content) {
    console.error(`${OUT} is stale; run pnpm docs:catalog`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${catalog.components.length} components).`);
} else {
  fs.writeFileSync(OUT, content);
  console.log(`Wrote ${OUT} (${catalog.components.length} components).`);
}
